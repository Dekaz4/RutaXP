local factionKeys = {Alliance = "A", Horde = "H"}

function ns:GetMapServicePoints(mapID)
    local entries = sites[mapID]
    local points = {}
    if not entries then return points end
    local faction = factionKeys[UnitFactionGroup("player")]
    local _, class = UnitClass("player")
    for _, site in ipairs(entries) do
        local category, side, x, y, name, frame, requiredClass = unpack(site)
        if (side == "AH" or side == faction) and (not requiredClass or requiredClass == class) then
            -- Era percentages can differ from the map Forever displays. Cache
            -- successful projections only; C_Map can be unavailable at login.
            local projected = site.projected
            if not projected then
                local pos = self:ResolveWaypointPoint({map = mapID, x = x, y = y, f = frame})
                if pos and pos.mapID == mapID then
                    projected = {category = category, name = name, x = pos.x, y = pos.y}
                    site.projected = projected
                end
            end
            if projected then points[#points + 1] = projected end
        end
    end
    return points
end
