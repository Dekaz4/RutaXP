#!/usr/bin/env python3
"""Vendor the pinned GPL walking engine and collision maps, reproducibly.

    python tools/vendor_pathing.py
    python tools/vendor_pathing.py --check

The source checkout defaults to .sources/SendaFH. All inputs are verified
against the pinned manifests and fixed hashes before anything is written.
Only namespaces, the private addon namespace and an early capability guard
change; routing algorithms and packed navigation bytes stay identical.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from typing import Iterable

ROOT = Path(__file__).resolve().parents[1]
COMMIT = "5d207e28e82e2c529143b21ace74fe88692f0067"
SPF_COMMIT = "b1ad5bd4bf579c781937af0e25f5233cc94b3726"
ADDON = Path("addon/SendaFH_Nav")
EXTRA_HASHES = {
    "API.lua": "45f5cca34dd5eaeaf34f546e3037fd7de20e4483ec56d4717520b3eab8489fca",
    "Nav/Nav.xml": "4739659fc822070064bef1748bcd93cf235065eae6882da640fe7f61870b5afb",
    "LICENSE": "c3056b39f2dafced20492bb270e339e94d6b2e4030f57f39b04b4193ea57dedf",
    "CREDITS.md": "1c963d2079d5d91164d951196300efe09a5df1a491680fffdd8eaae3fa456cb4",
    "UPSTREAM.json": "241b8568bb44619199b30c897d3bd18cbfba1c17b105808fe952b1699af87dbe",
    "PACK.json": "eecfb0b190704c9462e29bec883cfa69afd6837d200ae6e3e1ac93b8d3ac47ed",
}
SUBSTITUTIONS = {
    "SendaFHPathData": "RutaXPPathData",
    "SendaFHNavChokepoints": "RutaXPPathChokepoints",
    "SendaFH_NavEngine": "RutaXPPathEngine",
}
HEADER = (
    "-- RutaXP mechanical adaptation, 2026-10-20; tools/vendor_pathing.py.\n"
    f"-- Source: julen92/SendaFH@{COMMIT}; original notices follow.\n"
)
BOOTSTRAP = '''-- RutaXP's private walking namespace; keep installed pathing addons isolated.
local _, root = ...
root.PathingNamespace = {}
local enc = C_EncodingUtil
local method = Enum and Enum.CompressionMethod
RutaXPPathingSupported = type(enc)=="table" and type(enc.DecodeBase64)=="function"
    and type(enc.DecompressString)=="function" and type(method)=="table" and method.Zlib~=nil
    and type(C_Timer)=="table" and type(C_Timer.After)=="function"
root.PathingNamespace.supported = RutaXPPathingSupported
root.PathingNamespace.unsupportedReason = not RutaXPPathingSupported
    and "El cliente no ofrece decodificación Zlib o temporizadores para las rutas terrestres." or nil
-- These are private copies: neither SendaFH nor Shortest Path Forever data is reused.
RutaXPPathData = {}
RutaXPPathChokepoints = {}
'''
XML = '''<Ui xmlns="http://www.blizzard.com/wow/ui/">
    <!-- Generated by tools/vendor_pathing.py; load order matches the pinned upstream addon. -->
    <Script file="Bootstrap.lua"/>
    <Include file="Nav/Nav.xml"/>
    <Script file="Routing/PathGrid.lua"/>
    <Script file="Routing/Path.lua"/>
    <Script file="Routing/PathJobs.lua"/>
    <Script file="API.lua"/>
</Ui>
'''


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def safe_relative(name: str) -> Path:
    value = Path(name)
    if value.is_absolute() or ".." in value.parts or ":" in name or "\\" in name:
        raise ValueError(f"Unsafe source-manifest path: {name}")
    return value


def read_inputs(source: Path) -> dict[str, bytes]:
    """Verify all bytes against immutable source manifests before adapting."""
    base = source / ADDON
    for name, expected in EXTRA_HASHES.items():
        data = (base / name).read_bytes()
        if digest(data) != expected:
            raise ValueError(f"Pinned input changed: {name}")
    pack = json.loads((base / "PACK.json").read_text(encoding="utf-8"))
    upstream = json.loads((base / "UPSTREAM.json").read_text(encoding="utf-8"))
    if upstream.get("commit") != SPF_COMMIT:
        raise ValueError("The Shortest Path Forever commit does not match the pin")
    expected = {**EXTRA_HASHES, **pack["files"], **upstream["files"]}
    inputs = {}
    for name, sha in sorted(expected.items()):
        path = base / safe_relative(name)
        data = path.read_bytes()
        if digest(data) != sha:
            raise ValueError(f"Pinned input changed: {name}")
        inputs[name] = data
    # A checkout at a different commit may contain matching artifacts but must
    # not be represented as the pinned source checkout in the release.
    if (source / ".git").exists():
        head = subprocess.run(["git", "-C", str(source), "rev-parse", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
        if head != COMMIT:
            raise ValueError(f"Source checkout is {head}; expected {COMMIT}")
    return inputs


def adapt(name: str, data: bytes) -> bytes:
    if not name.endswith(".lua"):
        return data  # Original LICENSE, credits and manifests remain byte-identical.
    text = data.decode("utf-8")
    for old, new in SUBSTITUTIONS.items():
        text = text.replace(old, new)
    if name.startswith("Routing/"):
        declaration = "local ns = select(2, ...)"
        if text.count(declaration) != 1:
            raise ValueError(f"Unexpected namespace declaration in {name}")
        text = text.replace(declaration, "local root = select(2, ...)\nlocal ns = root.PathingNamespace", 1)
    elif name == "API.lua":
        declaration = "local _, ns = ..."
        if text.count(declaration) != 1:
            raise ValueError("Unexpected API namespace declaration")
        text = text.replace(declaration, "local _, root = ...\nlocal ns = root.PathingNamespace", 1)
    if name.startswith("Nav/"):
        # Lua still parses a file, but unsupported clients retain none of its
        # packed strings/tables. Bootstrap runs before every payload chunk.
        text = "if not RutaXPPathingSupported then return end\n" + text
    return (HEADER + text).encode("utf-8")


def render(source: Path) -> dict[str, bytes]:
    inputs = read_inputs(source)
    outputs = {name: adapt(name, data) for name, data in inputs.items()}
    outputs["Bootstrap.lua"] = BOOTSTRAP.encode("utf-8")
    outputs["Pathing.xml"] = XML.encode("utf-8")
    manifest = {
        "schema": 1,
        "source": {"repository": "https://github.com/julen92/SendaFH", "commit": COMMIT,
                   "directory": ADDON.as_posix(), "license": "GPL-3.0-or-later",
                   "pathingAuthor": "Cillian Berragan (Shortest Path Forever)",
                   "routingRepository": "https://github.com/cjber/shortest-path-forever",
                   "routingCommit": SPF_COMMIT, "routingVersion": "1.16.0",
                   "gridProduct": "wow_classic_beta", "gridBuild": "1.60.1.70374"},
        "adaptation": {"script": "tools/vendor_pathing.py", "date": "2026-10-20",
                       "substitutions": SUBSTITUTIONS,
                       "namespace": "The addon-private namespace is root.PathingNamespace",
                       "payloadGuard": "Nav Lua chunks return early when required decoding APIs are unavailable",
                       "algorithmChanges": False},
        "files": {name: {"source": f"{ADDON.as_posix()}/{name}",
                         "sourceSHA256": digest(inputs[name]), "sha256": digest(outputs[name])}
                  for name in sorted(inputs)},
        "generatedFiles": {name: {"sha256": digest(outputs[name])}
                           for name in ("Bootstrap.lua", "Pathing.xml")},
    }
    outputs["VENDORED.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    return outputs


def build(source: Path, destination: Path, check: bool = False) -> tuple[int, int]:
    source, destination = source.resolve(), destination.resolve()
    if source == destination or source in destination.parents or destination in source.parents:
        raise ValueError("Source and output must be separate directories")
    files = render(source)
    changed = []
    for name, data in files.items():
        target = destination / safe_relative(name)
        if not target.is_file() or target.read_bytes() != data:
            changed.append(name)
    if check and changed:
        raise ValueError("Vendored output differs: " + ", ".join(changed[:12]))
    if not check:
        for name in changed:
            target = destination / safe_relative(name)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(files[name])
    return len(files), sum(map(len, files.values()))


def main(argv: Iterable[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / ".sources/SendaFH")
    parser.add_argument("--output", type=Path, default=ROOT / "RutaXP/Pathing")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    count, size = build(args.source, args.output, args.check)
    print(f"{'Verified' if args.check else 'Vendored'} {count} files, {size:,} bytes, source {COMMIT}")


if __name__ == "__main__":
    main()
