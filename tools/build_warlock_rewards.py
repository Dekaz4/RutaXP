"""Build quest-reward hints for the Gnome Warlock's linked leveling chapters."""
import argparse
import json
from pathlib import Path

from review_human_rogue import ACCESSORIES, ROOT, SOURCE, item_attributes, lua_value, rewards, route, write_or_check

GNOME_WARLOCK = ("WARLOCK", "Gnome", "Alliance")
START = "forever/alliance/dwarf-gnome/01-dun-morogh"


def caster_gear(raw):
    attributes = item_attributes(raw, 256)
    if not attributes:
        return
    inv, req, cls, sub, stats = attributes
    if cls == 2 and sub == 19 and inv == 26:
        if min(stats.get(k, 0) for k in ("dmin", "dmax", "speed")) > 0:
            dps = (stats["dmin"] + stats["dmax"]) * 500 / stats["speed"]
            return dict(kind="Varita", stat="dps", value=round(dps, 1), inv=inv, level=req)
        return
    kind = None
    if cls == 4:
        if inv in (1, 3, 5, 6, 7, 8, 9, 10, 20) and sub == 1:
            kind = "Tela"
        elif inv == 23:
            kind = "Objeto de mano izquierda"
        else:
            kind = ACCESSORIES.get(inv)
    elif cls == 2:
        if sub == 10 and inv == 17:
            kind = "Bastón"
        elif inv in (13, 21):
            kind = {7: "Espada", 15: "Daga"}.get(sub)
    if kind:
        for stat in ("sp", "int", "sta"):
            if stats.get(stat, 0) <= 0:
                continue
            if stat == "sta" and (kind != "Tela" or any(stats.get(k, 0) for k in ("str", "agi", "ap"))):
                continue
            return dict(kind=kind, stat=stat, value=stats[stat], inv=inv, level=req)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / ".sources/SendaFH")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = json.loads((SOURCE / "leveling.json").read_bytes())
    chapters = list(route(document, START, GNOME_WARLOCK))
    items = rewards(document, chapters, args.source, persona=GNOME_WARLOCK, race_mask=64,
                    class_mask=256, equipment=caster_gear)
    lines = ["-- Generated by tools/build_warlock_rewards.py. See Licenses/PROVENANCE.txt.",
             "local _, ns = ...", "ns.warlockQuestRewards = {"]
    lines.extend(f"    [{qid}] = {lua_value(entries, compact=True)}," for qid, entries in items.items())
    write_or_check(ROOT / "RutaXP/WarlockRewardData.lua", "\n".join([*lines, "}", ""]), args.check)
    print(f"{len(chapters)} chapters, {len(items)} quests with documented caster equipment.")


if __name__ == "__main__":
    main()
