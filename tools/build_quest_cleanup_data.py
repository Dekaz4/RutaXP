"""Build the positive quest ID catalog used by the selective journal cleanup."""

import hashlib
from pathlib import Path

from lupa.lua51 import LuaRuntime, lua_type

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".sources/SendaFH/addon/SendaFH_QuestDB/Quests.lua"
SOURCE_HASH = "29571619906bc566fc1066c080646e323807963d855af75f468717d812c916b8"
OUTPUT = ROOT / "RutaXP/QuestCleanupData.lua"


def ids(value):
    if value is None:
        return []
    return list(value.values()) if lua_type(value) == "table" else [value]


def catalog():
    # Normalize checkout line endings before verifying the pinned Lua source.
    source = SOURCE.read_bytes().replace(b"\r\n", b"\n")
    if hashlib.sha256(source).hexdigest() != SOURCE_HASH:
        raise ValueError("The SendaFH quest database differs from the reviewed source")
    lua = LuaRuntime()
    db = lua.table()
    lua.globals().SendaFH = lua.table(QuestDB=db)
    quests = {}
    def add_data(kind, rows):
        if kind == "quests":
            quests.update(rows.items())
    db.AddData = add_data
    lua.execute(source.decode("utf8"))

    ordinary, prerequisites = [], {}
    for quest, row in sorted(quests.items()):
        parents = {abs(parent) for col in (10, 17) for parent in ids(row[col]) if parent}
        if parents:
            prerequisites[quest] = sorted(parents)
        # Only classify leveling quests with a known zone and NPCs on both ends.
        # Require a regular objective and exclude class, exclusive, event,
        # profession, holiday and item-start/issued-item records.
        if (0 < (row[2] or 0) < 60 and (row[13] or 0) > 0 and row[12] is not None
                and not any(row[i] is not None for i in (5, 9, 11, 14, 15, 16, 19))
                and all(ids(row[col]) and all(npc > 0 for npc in ids(row[col])) for col in (7, 8))):
            ordinary.append(quest)
    return ordinary, prerequisites


def render():
    ordinary, prerequisites = catalog()
    lines = ["-- Generated by tools/build_quest_cleanup_data.py from the pinned Forever quest database.",
             "local _, ns = ...", "ns.QuestCleanupData = {", "    ordinary = {"]
    for start in range(0, len(ordinary), 8):
        lines.append("        " + ", ".join(f"[{quest}]=true" for quest in ordinary[start:start + 8]) + ",")
    lines.extend(["    },", "    prerequisites = {"])
    for quest, parents in prerequisites.items():
        lines.append("        [%d]={%s}," % (quest, ", ".join(map(str, parents))))
    lines.extend(["    },", "}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf8", newline="\n")
