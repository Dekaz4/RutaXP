"""Extract public road crossings and fixed transports for rejoining a guide."""
import argparse
import hashlib
import json
from pathlib import Path

from lupa.luajit21 import LuaRuntime


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".sources/SendaFH"

PORT_NAMES = {
    "Booty Bay": "Bahía del Botín", "Ratchet": "Trinquete", "Menethil Harbor": "Puerto de Menethil",
    "Southshore": "Costasur", "Stormwind Harbor": "Puerto de Ventormenta", "Stormwind": "Ventormenta",
    "Steamwheedle Port": "Puerto Bonvapor", "Rut'theran Village": "Aldea Rut'theran",
    "Undercity": "Entrañas", "Ironforge": "Forjaz", "Darnassus": "Darnassus",
}


def taxi_names():
    """Use the same Spanish place names already presented by the route steps."""
    aliases = {
        16: "Refugio de la Zaga", 17: "Sentencia", 31: "Thalanaar", 33: "Cima del Espolón",
        41: "Bastión Plumaluna", 48: "Puesto del Veneno", 49: "Claro de la Luna",
        58: "Avanzada de Zoram'gar",
        64: "Punta Talrendis", 65: "Claro Ramaespolón", 66: "Campamento del Orvallo",
        69: "Claro de la Luna", 70: "Peñasco Llamarada", 71: "Vigilia de Morgan",
        72: "Fuerte Cenarion", 73: "Fuerte Cenarion", 74: "Puesto del Torio",
        75: "Puesto del Torio", 76: "Poblado Sañadiente",
    }
    counts = {}
    catalog = json.loads((ROOT / "RutaXP/Source/leveling.json").read_bytes())
    for chapter in catalog["guides"]:
        for step in chapter["steps"]:
            for goal in step["goals"]:
                label = goal.get("location")
                if not label or goal["t"] not in ("fly", "getfp"): continue
                for candidate in goal.get("candidates", []):
                    for dest in candidate.get("destinationNodes", []):
                        by_name = counts.setdefault(dest, {})
                        by_name[label] = by_name.get(label, 0) + 1
    for node, labels in counts.items():
        aliases.setdefault(node, max(labels, key=labels.get))
    return aliases


def quotation(name):
    return json.dumps(name, ensure_ascii=False)


def endpoint(values):
    map_id, x, y, frame, *name = values
    label = ", name=" + quotation(PORT_NAMES.get(name[0], name[0])) if name else ""
    return f'{{map={map_id}, x={x:g}, y={y:g}, f="{frame}"{label}}}'


def stopovers(timetable, transports):
    """Resolve intermediate calls in sailing order for Forever's three-port loop."""
    stops = {}
    for row in transports.values():
        service = timetable.services[row.id]
        if not service: continue
        for segment in service.routes.values():
            ports = stops.setdefault(segment.route, {})
            for side in ("a", "b"):
                port = row[side]
                for index in segment[side].values():
                    ports[index] = [port[n] for n in (5, 6, 7, 8, 1)]
    result = {}
    for row in transports.values():
        service = timetable.services[row.id]
        if not service or len(service.routes) != 1: continue
        segment = service.routes[1]
        route = timetable.routes[segment.route]
        if len(route.stops) != 3 or len(stops[segment.route]) != 3: continue
        if len(segment.a) != 1 or len(segment.b) != 1: continue
        a, b = segment.a[1], segment.b[1]
        for field, origin, destination in (("stopAB", a,b), ("stopBA", b,a)):
            via = origin % 3 + 1
            if via != destination:
                result[row.id, field] = stops[segment.route][via]
    return result


def pinned(path, checksum):
    data = (SOURCE / path).read_bytes()
    if hashlib.sha256(data).hexdigest() != checksum:
        raise ValueError(f"Unexpected travel data revision: {path}")
    return data.decode("utf-8-sig")


def render():
    roads = json.loads(pinned("tools/lib/travel/crossings.json",
        "d115a1b07b15cded9436da9fa7e617695a85b3ef9969dd8448e6afbef6943fbe"))
    catalog = pinned("addon/SendaFH/Nav/TravelData.lua",
        "1e7e2503c00b52fe96fa4001dc168ffb9d3805952dea4041c25dd6eb7f3c51a8")
    lua = LuaRuntime(unpack_returned_tuples=True)
    data, timetable = lua.eval("""function(code)
        local data, timetable
        assert(loadstring(code))("SendaFH", {
            Nav={RegisterTravelData=function(t) data=t end, RegisterCrossings=function() end},
            Transit={Register=function(t) timetable=t end}})
        return data, timetable
    end""")(catalog)
    lines = ["-- Verified crossings from SendaFH 5d207e2, Carbonite-Classic 4d06280.",
             "-- Source records, frames and licenses: Licenses/PROVENANCE.txt.",
             "-- Generated by tools/build_travel_connections.py.",
             "local _, ns = ...", "ns.GuideTravelConnections = {"]

    def add(kind, mask, a, b, one_way=False, extra=""):
        single = ", oneWay=true" if one_way else ""
        lines.append(f'    {{kind="{kind}", mask={mask}, a={endpoint(a)}, b={endpoint(b)}{single}{extra}}},')

    cities = {1453: 1, 1455: 1, 1457: 1, 1454: 2, 1456: 2, 1458: 2}
    for road in roads["crossings"]:
        a, b = ([road[key][field] for field in ("map", "x", "y")] + ["e"] for key in ("a", "b"))
        add("road", cities.get(a[0], cities.get(b[0], 3)), a, b)
    via = stopovers(timetable, data.transports)
    for category in ("transports", "portals"):
        entries = data[category]
        for i in range(1, len(entries) + 1):
            row = entries[i]
            a, b = ([row[key][n] for n in (5, 6, 7, 8, 1)] for key in ("a", "b"))
            if a[0] != b[0]:  # Same-map boats belong to authored itineraries.
                fields = [f'id={quotation(row.id)}']
                for key in ("ab","ba","waitA","waitB"):
                    if row[key] is not None: fields.append(f"{key}={row[key]:g}")
                for key in ("stopAB","stopBA"):
                    if (row.id,key) in via: fields.append(f"{key}={endpoint(via[row.id,key])}")
                add(row.kind or "portal", row.faction or 1, a, b, category == "portals", ", "+", ".join(fields))
    lines.extend(["}", "-- Physical taxi network. Availability is observed independently for each character.",
                  "ns.GuideTaxiNodes = {"])
    names = taxi_names()
    for row in sorted(data.taxi.values(), key=lambda v: v[1]):
        i, continent, _, _, m, x, y, mask, english = [row[n] for n in range(1,10)]
        name = quotation(names.get(i, english.partition(",")[0]))
        lines.append(f'    [{i}]={{id={i}, continent={continent}, map={m}, x={x:g}, y={y:g}, f="e", mask={mask}, name={name}}},')
    lines.extend(["}", "-- Directed, in-flight path lengths in yards.", "ns.GuideTaxiPaths = {"])
    distances = {}
    for i in range(1,len(data.flights)+1,3):
        origin, destination, length = [data.flights[i+j] for j in range(3)]
        distances.setdefault(origin,{})[destination] = length
    for origin, outgoing in sorted(distances.items()):
        entries = ", ".join(f"[{destination}]={length:g}" for destination,length in sorted(outgoing.items()))
        lines.append(f"    [{origin}]={{{entries}}},")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    target = ROOT / "RutaXP/TravelConnections.lua"
    result = render()
    if parser.parse_args().check:
        if target.read_text(encoding="utf-8") != result:
            raise SystemExit("Travel connections are stale")
    else:
        target.write_text(result, encoding="utf-8", newline="\n")
