"""Extract public road crossings and fixed transports for rejoining a guide."""
import argparse
import hashlib
import json
from pathlib import Path

from lupa.luajit21 import LuaRuntime


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".sources/SendaFH"


def pinned(path, checksum):
    data = (SOURCE / path).read_bytes()
    if hashlib.sha256(data).hexdigest() != checksum:
        raise ValueError(f"Unexpected travel data revision: {path}")
    return data.decode("utf-8-sig")


def render():
    roads = json.loads(pinned("tools/lib/travel/crossings.json",
        "d115a1b07b15cded9436da9fa7e617695a85b3ef9969dd8448e6afbef6943fbe"))
    catalog = pinned("addon/SendaFH/Nav/TravelData.lua",
        "1e7e2503c00b52fe96fa4001dc168ffb9d3805952dea4041c25dd6eb7f3c51a8")
    lua = LuaRuntime()
    data = lua.eval("""function(code)
        local data
        local function capture(t) data=t end
        assert(loadstring(code))("SendaFH", {Nav={RegisterTravelData=capture, RegisterCrossings=function() end}})
        return data
    end""")(catalog)
    lines = ["-- Verified crossings from SendaFH 5d207e2, Carbonite-Classic 4d06280.",
             "-- Source records, frames and licenses: Licenses/PROVENANCE.txt.",
             "-- Generated by tools/build_travel_connections.py.",
             "local _, ns = ...", "ns.GuideTravelConnections = {"]

    def add(kind, mask, a, b, one_way=False):
        def point(values):
            m, x, y, frame = values
            return f'{{map={m}, x={x:g}, y={y:g}, f="{frame}"}}'
        single = ", oneWay=true" if one_way else ""
        lines.append(f'    {{kind="{kind}", mask={mask}, a={point(a)}, b={point(b)}{single}}},')

    cities = {1453: 1, 1455: 1, 1457: 1, 1454: 2, 1456: 2, 1458: 2}
    for road in roads["crossings"]:
        a, b = ([road[key][field] for field in ("map", "x", "y")] + ["e"] for key in ("a", "b"))
        add("road", cities.get(a[0], cities.get(b[0], 3)), a, b)
    for category in ("transports", "portals"):
        entries = data[category]
        for i in range(1, len(entries) + 1):
            row = entries[i]
            a, b = ([row[key][n] for n in (5, 6, 7, 8)] for key in ("a", "b"))
            if a[0] != b[0]:  # Same-map boats belong to authored itineraries.
                add(row.kind or "portal", row.faction or 1, a, b, category == "portals")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    target = ROOT / "RutaXP/TravelConnections.lua"
    result = render()
    if parser.parse_args().check:
        if target.read_text(encoding="utf-8") != result:
            raise SystemExit("Travel connections are stale")
    else:
        target.write_text(result, encoding="utf-8", newline="\n")
