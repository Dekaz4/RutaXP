"""Build the factual quest/map crosswalk from RutaXP's last native route snapshot."""
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def build(snapshot):
    lines = ["-- Generated by tools/build_guide_legacy.py from the RutaXP 0.7 route data.",
             "-- Each row is the step's zone followed by its quest IDs (no guide text).",
             "local _, ns = ...", "ns.legacyGuideAnchors = {"]
    for guide in snapshot["guides"]:
        key = json.dumps(guide["id"])
        revision = guide.get("routeRevision", 1)
        lines.append(f"    [{key}] = {{revision={revision},")
        for step in guide["steps"]:
            goals = step.get("goals", [])
            zone = next((goal["map"] for goal in goals if goal.get("map")), guide.get("zone") or 0)
            quests = dict.fromkeys(goal["quest"] for goal in goals if goal.get("quest"))
            lines.append("        {" + ",".join(map(str, [zone, *quests])) + "},")
        # Older saves use the cursor of their own revision. Store the exceptions
        # to the identity mapping rather than duplicating the steps themselves.
        migrations = guide.get("progressMigrations", [])
        if migrations:
            lines.append("        migrations={")
            for m in migrations:
                exceptions = sorted((int(k), v) for k, v in m["stepMap"].items() if int(k) != v)
                entries = ",".join(f"[{k}]={v}" for k, v in exceptions)
                lines.append(f"            [{m['from']}]={{to={m['to']},count={m['previousStepCount']},{entries}}},")
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    source = ROOT / "RutaXP/Source/leveling.json"
    result = build(json.loads(source.read_text(encoding="utf8")))
    (ROOT / "RutaXP/GuideLegacyAnchors.lua").write_text(result, encoding="utf8", newline="\n")
