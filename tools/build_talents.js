// Helper to expand compact sequence: [['Talent Name', count, 'TreeName'], ...]
function expandSeq(seq, defaultTree, label) {
  const out = [];
  let level = 10;
  for (const item of seq) {
    const [talent, count, tree] = Array.isArray(item) ? item : [item.talent, item.count || 1, item.tree];
    const specTree = tree || defaultTree;
    for (let i = 0; i < count; i++) {
      out.push({ level: level++, tree: specTree, talent });
    }
  }
  if (out.length !== 51) {
    throw new Error(`${label}: sequence length is ${out.length}, expected 51`);
  }
  return out;
}

