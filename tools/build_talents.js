function luaStr(s) {
  return `"${String(s || '').replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
}

// DB2 CSV snapshots from https://wago.tools/db2/<table>/csv?build=<build>.
// The two localized files use &locale=esES. Keep each class on its reviewed
// build until its plans have also been checked against a newer tree.
async function readTalentData(build) {
  const sourcesDir = path.resolve(__dirname, '../.sources/SendaFH/data/sources');
  const { tables } = await loadTables({
    sourcesDir,
    build,
    offline: true,
    tables: TABLES,
  });
  const cacheDir = path.join(sourcesDir, 'wago', build);
  const tdEs = new Map(parseCsv(fs.readFileSync(path.join(cacheDir, 'TraitDefinition.esES.csv'), 'utf8')).map(r => [Number(r.ID), r]));
  const snEs = new Map(parseCsv(fs.readFileSync(path.join(cacheDir, 'SpellName.esES.csv'), 'utf8')).map(r => [Number(r.ID), r.Name_lang]));
  const entries = new Map(tables.TraitNodeEntry.map(r => [Number(r.ID), r]));
  return { tables, tdEs, snEs, entries };
}

async function main() {
  const buildMod = require('../.sources/SendaFH/tools/lib/talents/build');
  Object.assign(buildMod.CLASSES, CLASS_META);
  const baseData = await readTalentData(BUILD);
  const paladinData = await readTalentData(PALADIN_BUILD);
  const lines = [
    `-- Auto-generated by tools/build_talents.js from Forever DB2: Paladin ${PALADIN_BUILD}, other classes ${BUILD}.`,
    'local _, ns = ...',
    'ns.Talents = ns.Talents or {}',
    'local T = ns.Talents',
    '',
    'T.RaceGuides = {',
  ];

  for (const [raceKey, r] of Object.entries(RACE_GUIDES)) {
    lines.push(`\t[${luaStr(raceKey)}] = { name = ${luaStr(r.nameEs)}, faction = ${luaStr(r.faction)}, perks = ${luaStr(r.perks)}, tip = ${luaStr(r.tip)} },`);
  }
  lines.push('}', '');

  let totalBuilds = 0;
  let totalPicks = 0;

  for (const [cls, meta] of Object.entries(CLASS_META)) {
    const { tables, tdEs, snEs, entries } = cls === 'PALADIN' ? paladinData : baseData;
    const facts = treeFacts(tables, cls);
    // Filter out off-screen deprecated nodes (y >= 10000) and reverse edges (from.y > to.y)
    for (const id of Object.keys(facts.nodes).map(Number)) {
      if (facts.nodes[id].y >= 10000) {
        delete facts.nodes[id];
        for (const s of facts.specs) {
          const idx = s.indexOf(id);
          if (idx !== -1) s.splice(idx, 1);
        }
      } else {
        const entry = entries.get(facts.nodes[id].entry);
        const defEs = tdEs.get(Number(entry.TraitDefinitionID));
        const rawEs = (defEs && defEs.OverrideName_lang) || snEs.get(facts.nodes[id].spell) || facts.nodes[id].name;
        facts.nodes[id].nameEs = CUSTOM_ES[rawEs] || rawEs;
      }
    }
    facts.edges = facts.edges.filter(e => facts.nodes[e.from] && facts.nodes[e.to] && facts.nodes[e.from].y <= facts.nodes[e.to].y);

    // Resolve and validate all builds for this class
    const classPlans = PLANS[cls];
    const resolvedBuilds = [];
    for (const plan of classPlans) {
      const expanded = expandSeq(plan.seq, plan.spec, `${cls}/${plan.key}`);
      const ranks = {};
      const picks = [];
      const spent = (g) => (facts.groups[g] || []).reduce((s, id) => s + (ranks[id] || 0), 0);

      for (let i = 0; i < expanded.length; i++) {
        const step = expanded[i];
        const specIdx = meta.specs.indexOf(step.tree);
        if (specIdx === -1) { console.error(`${cls}/${plan.key}: unknown spec ${step.tree}`); break; }
        const hits = facts.specs[specIdx].filter(id => facts.nodes[id] && facts.nodes[id].name === step.talent);
        if (hits.length !== 1) {
          console.error(`${cls}/${plan.key} pick #${i + 1}: talent "${step.talent}" in ${step.tree} matched ${hits.length} nodes`);
          break;
        }
        const nodeID = hits[0];
        const node = facts.nodes[nodeID];
        const nextRank = (ranks[nodeID] || 0) + 1;
        if (nextRank > node.max) {
          console.error(`${cls}/${plan.key} pick #${i + 1} (${node.name}): rank ${nextRank} > max ${node.max}`);
          break;
        }
        for (const g of facts.gates[nodeID] || []) {
          if (spent(g.group) < g.need) {
            throw new Error(`${cls}/${plan.key} pick #${i + 1} (level ${step.level}, ${node.name}): needs ${g.need} points in tree, has ${spent(g.group)}`);
          }
        }
        for (const e of facts.edges) {
          if (e.to === nodeID) {
            const from = facts.nodes[e.from];
            if ((ranks[e.from] || 0) < from.max) {
              throw new Error(`${cls}/${plan.key} pick #${i + 1} (level ${step.level}, ${node.name}): needs prerequisite ${from.name} ${from.max}/${from.max}, has ${ranks[e.from] || 0}`);
            }
          }
        }
        ranks[nodeID] = nextRank;
        picks.push({ node: nodeID, rank: nextRank });
      }
      if (picks.length !== 51) throw new Error(`${cls}/${plan.key}: incomplete talent plan`);
      const distribution = [0, 0, 0];
      for (const pick of picks) distribution[facts.nodes[pick.node].spec - 1]++;
      resolvedBuilds.push({ ...plan, split: distribution.join('/'), picks });
      totalBuilds++;
      totalPicks += picks.length;
    }

    lines.push('T.Register({');
    lines.push(`\tclass = ${luaStr(cls)}, nameEs = ${luaStr(meta.nameEs)}, tree = ${facts.treeID}, prereq = "full",`);
    lines.push(`\tsummary = ${luaStr(meta.summary)},`);
    lines.push(`\tspecs = { ${meta.specsEs.map(luaStr).join(', ')} },`);
    lines.push('\tnodes = {');
    for (const id of Object.keys(facts.nodes).map(Number).sort((a, b) => a - b)) {
      const n = facts.nodes[id];
      lines.push(`\t\t[${id}] = { ${n.entry}, ${n.max}, ${n.spell}, ${n.spec}, ${n.row}, ${n.col}, ${luaStr(n.name)}, ${luaStr(n.nameEs)} },`);
    }
    lines.push('\t},');
    lines.push('\tgates = {');
    for (const id of Object.keys(facts.gates).map(Number).filter(id => facts.nodes[id]).sort((a, b) => a - b)) {
      lines.push(`\t\t[${id}] = { ${facts.gates[id].map(g => `{ ${g.group}, ${g.need} }`).join(', ')} },`);
    }
    lines.push('\t},');
    lines.push('\tgroups = {');
    for (const g of Object.keys(facts.groups).map(Number).sort((a, b) => a - b)) {
      lines.push(`\t\t[${g}] = { ${facts.groups[g].filter(id => facts.nodes[id]).join(', ')} },`);
    }
    lines.push('\t},');
    lines.push(`\tedges = { ${facts.edges.map(e => `{ ${e.from}, ${e.to} }`).join(', ')} },`);
    lines.push('\tbuilds = {');
    for (const b of resolvedBuilds) {
      const specNum = meta.specs.indexOf(b.spec) + 1;
      lines.push('\t\t{');
      lines.push(`\t\t\tkey = ${luaStr(b.key)}, spec = ${specNum}, specName = ${luaStr(meta.specsEs[specNum - 1])},`);
      lines.push(`\t\t\ttitle = ${luaStr(b.title)}, role = ${luaStr(b.role)}, recommended = ${b.recommended ? 'true' : 'false'}, split = ${luaStr(b.split)},`);
      lines.push(`\t\t\tstats = ${luaStr(b.stats)}, weapons = ${luaStr(b.weapons)}, skills = ${luaStr(b.skills)}, rotation = ${luaStr(b.rotation)},`);
      const rows = [];
      for (let i = 0; i < b.picks.length; i += 6) {
        rows.push(`\t\t\t\t${b.picks.slice(i, i + 6).map(p => `{ ${p.node}, ${p.rank} },`).join(' ')}`);
      }
      lines.push('\t\t\tpicks = {', ...rows, '\t\t\t},');
      lines.push('\t\t\tnotes = {');
      for (const lv of Object.keys(b.notes || {}).map(Number).sort((x, y) => x - y)) {
        lines.push(`\t\t\t\t[${lv}] = ${luaStr(b.notes[lv])},`);
      }
      lines.push('\t\t\t},');
      lines.push('\t\t},');
    }
    lines.push('\t},');
    lines.push('\ttrainerSpells = {');
    for (const s of (TRAINER_SPELLS[cls] || [])) {
      lines.push(`\t\t{ level = ${s[0]}, name = ${luaStr(s[1])}, prio = ${luaStr(s[2])}, tip = ${luaStr(s[3])} },`);
    }
    lines.push('\t},');
    lines.push('})', '');
  }

  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
  console.log(`Generated ${OUT_FILE}: 9 classes, ${totalBuilds} builds, ${totalPicks} validated picks.`);
}

main().catch(err => {
  console.error(err.message || err);
  process.exit(1);
});
