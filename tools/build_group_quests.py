"""Refresh group tags for routed quests and their prerequisites from the Forever quest listing."""
import argparse
import json
import re
from collections import defaultdict
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class QuestListing(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.rows = {}
        self.tag = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "tr":
            self.tag = attrs.get("data-type", "") if "data-name" in attrs else None
        elif tag == "a" and self.tag is not None:
            match = re.fullmatch(r"/forever/enUS/quest/(\d+)/", attrs.get("href", ""))
            if match:
                self.rows[int(match[1])] = self.tag
                self.tag = None

    def handle_endtag(self, tag):
        if tag == "tr":
            self.tag = None


def render(catalog, listing):
    relevant = set()
    for guide in catalog["guides"]:
        for step in guide["steps"]:
            for goal in step["goals"]:
                if goal.get("quest"):
                    relevant.add(goal["quest"])
                for field in ("pre", "preAll", "chainStarted"):
                    values = goal.get(field, [])
                    if isinstance(values, list):
                        relevant.update(values)
    groups = defaultdict(list)
    for quest in sorted(relevant):
        tag = listing.get(quest)
        if tag in {"elite", "dungeon", "raid", "group"}:
            groups[tag].append(quest)
    lines = ["-- Forever quest tags from https://zephras.com/forever/enUS/quest/.",
             "-- Generated by tools/build_group_quests.py; only routed quests and prerequisites.",
             "local _, ns = ...", "ns.Data = ns.Data or {}", "ns.Data.groupQuests = {"]
    for tag, ids in sorted(groups.items()):
        lines.append("    -- " + tag)
        for i in range(0, len(ids), 6):
            lines.append("    " + ", ".join(f"[{q}]=true" for q in ids[i:i+6]) + ",")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("listing", type=Path, help="Saved HTML from https://zephras.com/forever/enUS/quest/")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    reader = QuestListing()
    reader.feed(args.listing.read_text(encoding="utf-8"))
    if not all(reader.rows.get(q) == "elite" for q in (474, 98297, 98310)) or len(reader.rows) < 4000:
        raise SystemExit("Incomplete or incompatible quest listing")
    source = ROOT / "RutaXP/Source/leveling.json"
    content = render(json.loads(source.read_text(encoding="utf-8")), reader.rows)
    target = ROOT / "RutaXP/GroupQuestData.lua"
    if args.check:
        if content != target.read_text(encoding="utf-8"):
            raise SystemExit("GroupQuestData.lua needs regeneration")
    else:
        target.write_text(content, encoding="utf-8", newline="\n")
